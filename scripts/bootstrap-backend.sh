#!/usr/bin/env bash
# Point Terraform's S3 backend at a state bucket that belongs to the AWS account the
# current credentials are for, creating the bucket the first time.
#
# The bucket name is derived from the account ID, so nothing in the code is tied to one
# account: after switching to a new AWS Academy account, paste the new credentials and
# run this again (`make init`). Each account keeps its own state.
set -euo pipefail

PROFILE="${PROFILE:-academy}"
REGION="${REGION:-us-east-1}"
cd "$(dirname "$0")/.."

aws_() { aws --profile "$PROFILE" --region "$REGION" "$@"; }

ACCOUNT_ID="$(aws_ sts get-caller-identity --query Account --output text)"
BUCKET="tfstate-${ACCOUNT_ID}-${REGION}"
echo "AWS account ${ACCOUNT_ID} (profile ${PROFILE}, region ${REGION})"

if aws_ s3api head-bucket --bucket "$BUCKET" 2>/dev/null; then
  echo "state bucket s3://${BUCKET} already exists"
else
  echo "creating state bucket s3://${BUCKET}"
  if [ "$REGION" = "us-east-1" ]; then
    aws_ s3api create-bucket --bucket "$BUCKET" >/dev/null
  else
    aws_ s3api create-bucket --bucket "$BUCKET" --create-bucket-configuration "LocationConstraint=${REGION}" >/dev/null
  fi
  aws_ s3api put-bucket-versioning --bucket "$BUCKET" --versioning-configuration Status=Enabled
  aws_ s3api put-public-access-block --bucket "$BUCKET" --public-access-block-configuration \
    BlockPublicAcls=true,IgnorePublicAcls=true,BlockPublicPolicy=true,RestrictPublicBuckets=true
fi

cat > backend.hcl <<EOF
# Generated by scripts/bootstrap-backend.sh for account ${ACCOUNT_ID}. Not committed.
bucket  = "${BUCKET}"
region  = "${REGION}"
profile = "${PROFILE}"
EOF

# -reconfigure, not -migrate-state: a new account starts with fresh state (the old
# account's resources are not reachable from here anyway).
terraform init -reconfigure -input=false -backend-config=backend.hcl
